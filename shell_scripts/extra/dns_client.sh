# UPDATE THE SYSTEM PACKAGE DATABASE
sudo apt update

# INSTALL NET-TOOLS TO PROVIDE LEGACY COMMANDS LIKE IFCONFIG AND ROUTE
sudo apt install net-tools -y

# OVERWRITE THE SYSTEMD-RESOLVED CONFIGURATION TO USE A SPECIFIC REMOTE DNS SERVER
cat <<EOF | sudo tee /etc/systemd/resolved.conf
[Resolve]
DNS=10.0.1.10
EOF

# RESTART THE SYSTEMD-RESOLVED SERVICE TO APPLY THE NEW DNS SETTINGS
sudo service systemd-resolved restart

# GENERATE THE NETWORK CONFIGURATION FILES FROM THE NETPLAN YAML DEFINITIONS
sudo netplan generate

# APPLY THE NETWORK CONFIGURATION CHANGES IMMEDIATELY
sudo netplan apply

# MANUALLY OVERWRITE THE RESOLV.CONF FILE TO FORCE THE USE OF THE REMOTE NAMESERVER
cat <<EOF | sudo tee /etc/resolv.conf
nameserver 10.0.1.10
EOF

