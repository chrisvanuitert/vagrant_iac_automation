# PERMANENTLY CHANGE THE SYSTEM HOSTNAME TO MANAGEDNODE
sudo hostnamectl set-hostname managednode

# ADD THE CONTROL NODE IP AND HOSTNAME TO THE LOCAL HOSTS FILE FOR DNS RESOLUTION
echo "10.0.1.10 controlnode" | sudo tee -a /etc/hosts

# ADD THE MANAGED NODE IP AND HOSTNAME TO THE LOCAL HOSTS FILE
echo "10.0.1.11 managednode" | sudo tee -a /etc/hosts

# ENABLE PUBLIC KEY AUTHENTICATION IN THE SSH DAEMON CONFIGURATION
echo "PubkeyAuthentication yes" | sudo tee -a /etc/ssh/sshd_config

# DISABLE PASSWORD-BASED LOGIN TO ENFORCE KEY-ONLY SECURITY
echo "PasswordAuthentication no" | sudo tee -a /etc/ssh/sshd_config

# CREATE THE .SSH DIRECTORY IN THE USER HOME IF IT DOES NOT ALREADY EXIST
mkdir -p ~/.ssh

# APPEND THE SPECIFIED PUBLIC KEY TO THE AUTHORIZED_KEYS FILE FOR PASSWORDLESS ACCESS
echo "PASTE_PUBLIC_KEY_HERE" >> ~/.ssh/authorized_keys

# SET RESTRICTIVE DIRECTORY PERMISSIONS (OWNER READ/WRITE/EXECUTE ONLY)
chmod 700 ~/.ssh

# SET RESTRICTIVE FILE PERMISSIONS (OWNER READ/WRITE ONLY)
chmod 600 ~/.ssh/authorized_keys

# RESTART THE SSH SERVICE TO APPLY THE NEW SECURITY AND AUTHENTICATION SETTINGS
sudo systemctl restart sshd